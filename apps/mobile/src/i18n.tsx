type I18nContextValue = {
  locale: Locale;
  /** true when Arabic is active — use `rowDirection(isRtl)` for rows, not Yoga `direction`. */
  isRtl: boolean;
  directionStyle: ViewStyle;
  t: (typeof dictionary)[Locale];
  toggleLocale: () => void;
};

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export function I18nProvider({ children }: PropsWithChildren) {
  const [locale, setLocale] = useState<Locale>('ar');

  useEffect(() => {
    AsyncStorage.getItem(localeKey).then((storedLocale) => {
      if (storedLocale === 'ar' || storedLocale === 'en') setLocale(storedLocale);
    });
  }, []);

  const toggleLocale = () => {
    setLocale((current) => {
      const next = current === 'ar' ? 'en' : 'ar';
      AsyncStorage.setItem(localeKey, next).catch(() => undefined);
      return next;
    });
  };

  const isRtl = locale === 'ar';

  const value = useMemo(
    () => ({
      locale,
      isRtl,
      directionStyle: { flex: 1 },
      t: dictionary[locale],
      toggleLocale
    }),
    [isRtl, locale]
  );

  return (
    <I18nContext.Provider value={value}>
      <View style={value.directionStyle}>{children}</View>
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}
